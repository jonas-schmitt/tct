func writeGoStdlibScanTestFile(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir for %s: %v", path, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

var goStdlibScanTestIncludedFiles = map[string]string{
	"src/alpha/alpha.go": `package alpha

func Add(x int) int {
	return x + 1
}
`,
	"src/alpha/alpha_test.go": `package alpha

import "testing"

func TestAdd(t *testing.T) {
	if Add(1) != 2 {
		t.Fatal("add")
	}
}
`,
	"src/beta/cgo.go": `package beta

/*
#include <stdio.h>
*/
import "C"

func UsesC() {}
`,
	"src/beta/generated.go": `// Code generated by tct-fixture. DO NOT EDIT.

package beta

func Generated() {}
`,
	"src/beta/tagged.go": `//go:build linux

package beta

func Tagged() {}
`,
	"src/beta/broken.go": `package beta

func Broken(
`,
}

var goStdlibScanTestExcludedFiles = map[string]string{
	"src/alpha/testdata/skip.go": "package skip\n",
	"src/vendor/vlib/vlib.go":    "package vlib\n",
	"src/.hidden/hidden.go":      "package hidden\n",
}

func writeGoStdlibScanTestCorpus(t *testing.T) string {
	t.Helper()
	goroot := t.TempDir()
	for rel, content := range goStdlibScanTestIncludedFiles {
		writeGoStdlibScanTestFile(t, goroot, rel, content)
	}
	for rel, content := range goStdlibScanTestExcludedFiles {
		writeGoStdlibScanTestFile(t, goroot, rel, content)
	}
	writeGoStdlibScanTestFile(t, goroot, "src/alpha/README.md", "not a go file\n")
	return goroot
}

func assertGoStdlibScanFlags(t *testing.T, record goStdlibFileRecord, isTest, isBuildConstrained, isCgo, isGenerated, parseFailed bool) {
	t.Helper()
	if record.IsTest != isTest {
		t.Fatalf("%s is_test = %v, want %v", record.Path, record.IsTest, isTest)
	}
	if record.IsBuildConstrained != isBuildConstrained {
		t.Fatalf("%s is_build_constrained = %v, want %v", record.Path, record.IsBuildConstrained, isBuildConstrained)
	}
	if record.IsCgo != isCgo {
		t.Fatalf("%s is_cgo = %v, want %v", record.Path, record.IsCgo, isCgo)
	}
	if record.IsGenerated != isGenerated {
		t.Fatalf("%s is_generated = %v, want %v", record.Path, record.IsGenerated, isGenerated)
	}
	if record.ParseFailed != parseFailed {
		t.Fatalf("%s parse_failed = %v, want %v", record.Path, record.ParseFailed, parseFailed)
	}
}

func TestEnumerateGoStdlibSourceClassifiesMiniatureCorpus(t *testing.T) {
	goroot := writeGoStdlibScanTestCorpus(t)

	enumeration, err := enumerateGoStdlibSource(goroot)
	if err != nil {
		t.Fatalf("enumerate: %v", err)
	}

	if len(enumeration.Records) != len(goStdlibScanTestIncludedFiles) {
		t.Fatalf("record count = %d, want %d", len(enumeration.Records), len(goStdlibScanTestIncludedFiles))
	}
	if !sort.SliceIsSorted(enumeration.Records, func(i, j int) bool {
		return enumeration.Records[i].Path < enumeration.Records[j].Path
	}) {
		t.Fatalf("records are not sorted by path")
	}

	wantBytes := int64(0)
	for _, content := range goStdlibScanTestIncludedFiles {
		wantBytes += int64(len(content))
	}
	if enumeration.TotalSourceBytes != wantBytes {
		t.Fatalf("total source bytes = %d, want %d", enumeration.TotalSourceBytes, wantBytes)
	}

	if enumeration.ExcludedDirCounts.Testdata != 1 {
		t.Fatalf("testdata dir count = %d, want 1", enumeration.ExcludedDirCounts.Testdata)
	}
	if enumeration.ExcludedDirCounts.Vendor != 1 {
		t.Fatalf("vendor dir count = %d, want 1", enumeration.ExcludedDirCounts.Vendor)
	}
	if enumeration.ExcludedDirCounts.DotDirs != 1 {
		t.Fatalf("dot dir count = %d, want 1", enumeration.ExcludedDirCounts.DotDirs)
	}
	if enumeration.SkippedNonGoFiles != 1 {
		t.Fatalf("skipped non-go files = %d, want 1", enumeration.SkippedNonGoFiles)
	}

	counts := enumeration.classificationCounts()
	if counts.IsTest != 1 {
		t.Fatalf("is_test count = %d, want 1", counts.IsTest)
	}
	if counts.IsBuildConstrained != 1 {
		t.Fatalf("is_build_constrained count = %d, want 1", counts.IsBuildConstrained)
	}
	if counts.IsCgo != 1 {
		t.Fatalf("is_cgo count = %d, want 1", counts.IsCgo)
	}
	if counts.IsGenerated != 1 {
		t.Fatalf("is_generated count = %d, want 1", counts.IsGenerated)
	}

	failures := enumeration.parseFailures()
	if len(failures) != 1 {
		t.Fatalf("parse failure count = %d, want 1", len(failures))
	}
	if failures[0].Path != "src/beta/broken.go" {
		t.Fatalf("parse failure path = %q, want src/beta/broken.go", failures[0].Path)
	}
	if failures[0].Error == "" {
		t.Fatalf("parse failure error is empty")
	}
	if got := enumeration.denominator(); got != len(goStdlibScanTestIncludedFiles)-1 {
		t.Fatalf("denominator = %d, want %d", got, len(goStdlibScanTestIncludedFiles)-1)
	}

	byPath := map[string]goStdlibFileRecord{}
	for _, record := range enumeration.Records {
		byPath[record.Path] = record
	}
	for rel := range goStdlibScanTestExcludedFiles {
		if _, ok := byPath[rel]; ok {
			t.Fatalf("excluded file %s was enumerated", rel)
		}
	}
	for rel, content := range goStdlibScanTestIncludedFiles {
		record, ok := byPath[rel]
		if !ok {
			t.Fatalf("missing record for %s", rel)
		}
		if len(record.SHA256) != 64 {
			t.Fatalf("%s sha256 length = %d, want 64", rel, len(record.SHA256))
		}
		if record.Bytes != int64(len(content)) {
			t.Fatalf("%s bytes = %d, want %d", rel, record.Bytes, len(content))
		}
	}

	assertGoStdlibScanFlags(t, byPath["src/alpha/alpha.go"], false, false, false, false, false)
	assertGoStdlibScanFlags(t, byPath["src/alpha/alpha_test.go"], true, false, false, false, false)
	assertGoStdlibScanFlags(t, byPath["src/beta/cgo.go"], false, false, true, false, false)
	assertGoStdlibScanFlags(t, byPath["src/beta/generated.go"], false, false, false, true, false)
	assertGoStdlibScanFlags(t, byPath["src/beta/tagged.go"], false, true, false, false, false)
	assertGoStdlibScanFlags(t, byPath["src/beta/broken.go"], false, false, false, false, true)
	if byPath["src/beta/broken.go"].ParseError == "" {
		t.Fatalf("broken.go parse_error is empty")
	}
}

func TestParseGoListPackagesParsesPipeSeparatedLines(t *testing.T) {
	output := "fmt|/x/src/fmt|print.go,scan.go\nvendor/foo|/x/src/vendor/foo|v.go\n\n"
	packages, err := parseGoListPackages([]byte(output))
	if err != nil {
		t.Fatalf("parse go list output: %v", err)
	}
	if len(packages) != 2 {
		t.Fatalf("package count = %d, want 2", len(packages))
	}
	if packages[0].ImportPath != "fmt" || packages[0].Dir != "/x/src/fmt" {
		t.Fatalf("unexpected first package: %#v", packages[0])
	}
	if len(packages[0].GoFiles) != 2 || packages[0].GoFiles[0] != "print.go" || packages[0].GoFiles[1] != "scan.go" {
		t.Fatalf("unexpected go files: %#v", packages[0].GoFiles)
	}
	if packages[1].ImportPath != "vendor/foo" {
		t.Fatalf("unexpected second package: %#v", packages[1])
	}

	if _, err := parseGoListPackages([]byte("garbage-without-pipes\n")); err == nil {
		t.Fatalf("malformed go list line did not error")
	}
}

func TestCrossCheckGoListPackagesReportsVendorSkipAndMissing(t *testing.T) {
	goroot := filepath.FromSlash("/fake/goroot")
	walked := map[string]bool{"src/fmt/print.go": true}
	packages := []goListPackage{
		{
			ImportPath: "fmt",
			Dir:        filepath.Join(goroot, "src", "fmt"),
			GoFiles:    []string{"print.go", "scan.go"},
		},
		{
			ImportPath: "vendor/golang.org/x/net/http2/hpack",
			Dir:        filepath.Join(goroot, "src", "vendor", "golang.org", "x", "net", "http2", "hpack"),
			GoFiles:    []string{"hpack.go"},
		},
	}

	check := crossCheckGoListPackages(packages, goroot, walked)
	if check.PackageCount != 1 {
		t.Fatalf("package count = %d, want 1", check.PackageCount)
	}
	if check.VendorPackagesSkipped != 1 {
		t.Fatalf("vendor packages skipped = %d, want 1", check.VendorPackagesSkipped)
	}
	if check.GoFilesCount != 2 {
		t.Fatalf("go files count = %d, want 2", check.GoFilesCount)
	}
	if check.MissingCount != 1 || len(check.MissingFromWalk) != 1 || check.MissingFromWalk[0] != "src/fmt/scan.go" {
		t.Fatalf("unexpected missing delta: count=%d list=%#v", check.MissingCount, check.MissingFromWalk)
	}
	if check.Status != "missing_files" {
		t.Fatalf("status = %q, want missing_files", check.Status)
	}

	walked["src/fmt/scan.go"] = true
	check = crossCheckGoListPackages(packages, goroot, walked)
	if check.Status != "passed" {
		t.Fatalf("status = %q, want passed", check.Status)
	}
	if check.MissingCount != 0 || len(check.MissingFromWalk) != 0 {
		t.Fatalf("unexpected missing delta after fill: count=%d list=%#v", check.MissingCount, check.MissingFromWalk)
	}
}

func TestHasGoBuildConstraintDetectsHeaderConstraintsOnly(t *testing.T) {
	cases := []struct {
		name   string
		source string
		want   bool
	}{
		{"go_build_line", "//go:build linux\n\npackage a\n", true},
		{"plus_build_line", "// +build linux\n\npackage a\n", true},
		{"both_lines", "//go:build linux\n// +build linux\n\npackage a\n", true},
		{"plain_comment_header", "// regular comment\n/*\nblock comment\n*/\npackage a\n", false},
		{"constraint_text_in_string", "package a\n\nvar s = \"//go:build linux\"\n", false},
		{"constraint_after_package_clause", "package a\n\n//go:build linux\n", false},
		{"constraint_inside_block_comment", "/*\n//go:build linux\n*/\npackage a\n", false},
	}
	for _, testCase := range cases {
		if got := hasGoBuildConstraint([]byte(testCase.source)); got != testCase.want {
			t.Fatalf("%s: hasGoBuildConstraint = %v, want %v", testCase.name, got, testCase.want)
		}
	}
}

func TestGeneratedMarkerFallbackScansPrePackageHeader(t *testing.T) {
	withMarker := "// Code generated by tct-fixture. DO NOT EDIT.\npackage a\nfunc Broken(\n"
	if !hasGeneratedMarkerFallback([]byte(withMarker)) {
		t.Fatalf("pre-package generated marker not detected")
	}
	afterPackage := "package a\n// Code generated by tct-fixture. DO NOT EDIT.\nfunc Broken(\n"
	if hasGeneratedMarkerFallback([]byte(afterPackage)) {
		t.Fatalf("post-package generated marker should not be detected")
	}
}

