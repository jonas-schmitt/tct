func TestBuildGoSyntaxSelectionReportRecordsCandidatesAndExclusions(t *testing.T) {
	root := t.TempDir()
	writeGoSyntaxSelectionTestFile(t, root, "alpha/alpha.go", `package alpha

func Add(x int) int {
	if x > 0 {
		return x + 1
	}
	return 0
}
`)
	writeGoSyntaxSelectionTestFile(t, root, "alpha/dupe.go", `package alpha

func Sub(x int) int {
	if x > 0 {
		return x + 1
	}
	return 0
}
`)
	writeGoSyntaxSelectionTestFile(t, root, "beta/generated.go", `// Code generated by fixture. DO NOT EDIT.
package beta

func Generated() {}
`)
	writeGoSyntaxSelectionTestFile(t, root, "beta/cgo.go", `package beta

import "C"

func UsesC() {}
`)
	writeGoSyntaxSelectionTestFile(t, root, "beta/broken.go", `package beta

func Broken(
`)
	writeGoSyntaxSelectionTestFile(t, root, "beta/large.go", `package beta

var Payload = "`+longGoSyntaxSelectionString(600)+`"
`)

	report, err := buildGoSyntaxSelectionReport(goSyntaxSelectionConfig{
		SourceRoot:       root,
		CorpusID:         "fixture-selection",
		MaxFiles:         2,
		MaxFileBytes:     512,
		MaxTotalBytes:    1024,
		License:          "BSD-3-Clause",
		LicenseTextPath:  "LICENSE",
		SourceRevision:   "fixture",
		SourceURIPrefix:  "https://example.invalid/go/src",
		ExcludeGenerated: true,
		ExcludeCgo:       true,
		DedupeShapes:     true,
		IncludeTestFiles: true,
		SelectionNote:    "fixture",
	})
	if err != nil {
		t.Fatalf("build report: %v", err)
	}

	if report.Status != "ready" {
		t.Fatalf("status = %q, want ready", report.Status)
	}
	if report.GoVersion != runtime.Version() {
		t.Fatalf("go version = %q, want %q", report.GoVersion, runtime.Version())
	}
	if report.GoRoot == "" {
		t.Fatalf("go root should be recorded")
	}
	if report.GoVersionCheck != goSyntaxVersionCheckSkipped {
		t.Fatalf("go version check = %q, want %q", report.GoVersionCheck, goSyntaxVersionCheckSkipped)
	}
	if report.SourceFileCount != 6 {
		t.Fatalf("source file count = %d, want 6", report.SourceFileCount)
	}
	if report.CandidateCount != 1 {
		t.Fatalf("candidate count = %d, want 1", report.CandidateCount)
	}
	if report.SelectedCount != 1 {
		t.Fatalf("selected count = %d, want 1", report.SelectedCount)
	}
	if report.SelectedCandidates[0].ManifestPath != "alpha/alpha.go" {
		t.Fatalf("selected path = %q, want alpha/alpha.go", report.SelectedCandidates[0].ManifestPath)
	}
	if report.SelectedCandidates[0].SourceURI != "https://example.invalid/go/src/alpha/alpha.go" {
		t.Fatalf("source uri = %q", report.SelectedCandidates[0].SourceURI)
	}
	if len(report.SelectedCandidates[0].File.SHA256) != 64 {
		t.Fatalf("sha length = %d, want 64", len(report.SelectedCandidates[0].File.SHA256))
	}

	wantReasons := map[string]bool{
		"cgo_import":      true,
		"duplicate_shape": true,
		"generated_file":  true,
		"parser_error":    true,
		"too_large":       true,
	}
	gotReasons := map[string]bool{}
	for _, exclusion := range report.Exclusions {
		gotReasons[exclusion.Reason] = true
	}
	for reason := range wantReasons {
		if !gotReasons[reason] {
			t.Fatalf("missing exclusion reason %q in %#v", reason, gotReasons)
		}
	}

	if !goSyntaxSelectionHasConstruct(report.ConstructCoverage, "if_statement") {
		t.Fatalf("construct coverage did not include if_statement")
	}
	if !goSyntaxSelectionHasConstruct(report.SelectedCandidates[0].Constructs, "binary_expression") {
		t.Fatalf("candidate constructs did not include binary_expression")
	}
	if report.ClaimBoundaries.ArenaIRPromotion {
		t.Fatalf("arena IR promotion should remain blocked")
	}
	if report.ClaimBoundaries.GeneratedCodecChanged {
		t.Fatalf("selection harness should not report generated-codec changes")
	}
}

func TestBuildGoSyntaxSelectionReportCanExcludeExistingManifestEntries(t *testing.T) {
	root := t.TempDir()
	writeGoSyntaxSelectionTestFile(t, root, "alpha/alpha.go", `package alpha

func Add(x int) int {
	return x + 1
}
`)
	writeGoSyntaxSelectionTestFile(t, root, "beta/beta.go", `package beta

func Keep(x int) int {
	return x - 1
}
`)
	manifestPath := filepath.Join(root, "existing.json")
	if err := os.WriteFile(manifestPath, []byte(`{
  "entries": [
    { "manifest_path": "alpha/alpha.go" }
  ]
}
`), 0o644); err != nil {
		t.Fatalf("write existing manifest: %v", err)
	}

	report, err := buildGoSyntaxSelectionReport(goSyntaxSelectionConfig{
		SourceRoot:       root,
		ExistingManifest: manifestPath,
		ExcludeExisting:  true,
		CorpusID:         "fixture-selection",
		MaxFiles:         2,
		MaxFileBytes:     512,
		MaxTotalBytes:    1024,
		License:          "BSD-3-Clause",
		SourceRevision:   "fixture",
		SourceURIPrefix:  "https://example.invalid/go/src",
		ExcludeGenerated: true,
		ExcludeCgo:       true,
		IncludeTestFiles: true,
		SelectionNote:    "fixture",
	})
	if err != nil {
		t.Fatalf("build report: %v", err)
	}
	if report.ExistingManifest == nil {
		t.Fatalf("expected existing manifest summary")
	}
	if report.ExistingManifest.EntryCount != 1 {
		t.Fatalf("existing manifest entry count = %d, want 1", report.ExistingManifest.EntryCount)
	}
	if report.CandidateCount != 1 || report.Candidates[0].ManifestPath != "beta/beta.go" {
		t.Fatalf("candidate set = %#v, want only beta/beta.go", report.Candidates)
	}
	if report.ExistingCandidates != 0 || report.NewCandidates != 1 {
		t.Fatalf("existing/new counts = %d/%d, want 0/1", report.ExistingCandidates, report.NewCandidates)
	}
	if !goSyntaxSelectionHasExclusion(report.Exclusions, "existing_manifest_entry") {
		t.Fatalf("missing existing_manifest_entry exclusion: %#v", report.Exclusions)
	}
}

func TestBuildGoSyntaxSelectionReportCanExcludeReportIngestionRecords(t *testing.T) {
	root := t.TempDir()
	writeGoSyntaxSelectionTestFile(t, root, "alpha/alpha.go", `package alpha

func Add(x int) int {
	return x + 1
}
`)
	writeGoSyntaxSelectionTestFile(t, root, "beta/beta.go", `package beta

func Keep(x int) int {
	return x - 1
}
`)
	writeGoSyntaxSelectionTestFile(t, root, "gamma/gamma.go", `package beta

func Keep(x int) int {
	return x - 1
}
`)
	betaSHA := hashGoSyntaxSelectionFileForTest(t, filepath.Join(root, "beta", "beta.go"))
	reportIngestionPath := filepath.Join(root, "report-ingestion.json")
	if err := os.WriteFile(reportIngestionPath, []byte(`{
  "records": [
    { "manifest_path": "alpha/alpha.go", "source_sha256": "`+strings.Repeat("a", 64)+`" },
    { "manifest_path": "already-by-sha.go", "source_sha256": "`+betaSHA+`" }
  ]
}
`), 0o644); err != nil {
		t.Fatalf("write report-ingestion manifest: %v", err)
	}

	report, err := buildGoSyntaxSelectionReport(goSyntaxSelectionConfig{
		SourceRoot:                     root,
		ExcludeReportIngestionManifest: reportIngestionPath,
		CorpusID:                       "fixture-selection",
		MaxFiles:                       4,
		MaxFileBytes:                   512,
		MaxTotalBytes:                  2048,
		License:                        "BSD-3-Clause",
		SourceRevision:                 "fixture",
		SourceURIPrefix:                "https://example.invalid/go/src",
		ExcludeGenerated:               true,
		ExcludeCgo:                     true,
		IncludeTestFiles:               true,
		SelectionNote:                  "fixture",
	})
	if err != nil {
		t.Fatalf("build report: %v", err)
	}
	if report.ReportIngestionExclusion == nil {
		t.Fatalf("expected report-ingestion exclusion summary")
	}
	if report.ReportIngestionExclusion.RecordCount != 2 {
		t.Fatalf("report-ingestion record count = %d, want 2", report.ReportIngestionExclusion.RecordCount)
	}
	if len(report.ReportIngestionExclusion.SHA256) != 64 {
		t.Fatalf("report-ingestion manifest sha length = %d, want 64", len(report.ReportIngestionExclusion.SHA256))
	}
	if report.CandidateCount != 0 {
		t.Fatalf("candidate count = %d, want 0; candidates=%#v", report.CandidateCount, report.Candidates)
	}
	if report.Status != "blocked_no_candidates" {
		t.Fatalf("status = %q, want blocked_no_candidates", report.Status)
	}
	if !goSyntaxSelectionHasExclusion(report.Exclusions, "report_ingestion_manifest_record") {
		t.Fatalf("missing report_ingestion_manifest_record exclusion: %#v", report.Exclusions)
	}
}

func TestBuildGoSyntaxSelectionReportRejectsGoRevisionMismatchWithoutOverride(t *testing.T) {
	root := t.TempDir()
	writeGoSyntaxSelectionTestFile(t, root, "alpha/alpha.go", `package alpha

func Keep() {}
`)

	_, err := buildGoSyntaxSelectionReport(goSyntaxSelectionConfig{
		SourceRoot:       root,
		CorpusID:         "fixture-selection",
		MaxFiles:         1,
		MaxFileBytes:     512,
		MaxTotalBytes:    512,
		License:          "BSD-3-Clause",
		SourceRevision:   "go0.0.0",
		SourceURIPrefix:  "https://example.invalid/go/src",
		ExcludeGenerated: true,
		ExcludeCgo:       true,
		IncludeTestFiles: true,
		SelectionNote:    "fixture",
	})
	if err == nil {
		t.Fatalf("expected Go version mismatch error")
	}
	if !strings.Contains(err.Error(), "GO VERSION MISMATCH") {
		t.Fatalf("mismatch error = %q", err)
	}

	report, err := buildGoSyntaxSelectionReport(goSyntaxSelectionConfig{
		SourceRoot:             root,
		CorpusID:               "fixture-selection",
		MaxFiles:               1,
		MaxFileBytes:           512,
		MaxTotalBytes:          512,
		License:                "BSD-3-Clause",
		SourceRevision:         "go0.0.0",
		SourceURIPrefix:        "https://example.invalid/go/src",
		AllowGoVersionMismatch: true,
		ExcludeGenerated:       true,
		ExcludeCgo:             true,
		IncludeTestFiles:       true,
		SelectionNote:          "fixture",
	})
	if err != nil {
		t.Fatalf("override build report: %v", err)
	}
	if report.GoVersionCheck != goSyntaxVersionCheckOverride {
		t.Fatalf("go version check = %q, want %q", report.GoVersionCheck, goSyntaxVersionCheckOverride)
	}
	if !report.SelectionPolicy.AllowGoVersionMismatch {
		t.Fatalf("selection policy should record mismatch override")
	}
}

func writeGoSyntaxSelectionTestFile(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir for %s: %v", rel, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", rel, err)
	}
}

func hashGoSyntaxSelectionFileForTest(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return hashGoSyntaxSelectionBytes(data)
}

func longGoSyntaxSelectionString(length int) string {
	data := make([]byte, length)
	for i := range data {
		data[i] = 'x'
	}
	return string(data)
}

func goSyntaxSelectionHasConstruct(constructs []goSyntaxSelectionConstruct, name string) bool {
	for _, construct := range constructs {
		if construct.Construct == name {
			return true
		}
	}
	return false
}

func goSyntaxSelectionHasExclusion(exclusions []goSyntaxSelectionExclusion, reason string) bool {
	for _, exclusion := range exclusions {
		if exclusion.Reason == reason {
			return true
		}
	}
	return false
}
